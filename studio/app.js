// Results are generated by real Google OR-Tools CP-SAT in GitHub CI, not in this browser.
// GitHub Pages has no Python runtime. Current edits are checked but DO NOT re-run CP-SAT.
async function loadSolved(id){
 if(solutionCache.has(id))return solutionCache.get(id);
 try{
  const response=await fetch('./solutions/'+encodeURIComponent(id)+'.json',{cache:'no-store'});
  if(!response.ok)throw Error('no solver results');
  const result=await response.json();
  if(result.schema_version!=='cp-sat-v1'||result.engine!=='Google OR-Tools CP-SAT'||result.site_id!==id)throw Error('solver data mismatch');
  solutionCache.set(id,result);
  return result;
 }catch{return null;}
}
function fromSolved(site,data,index){
 const candidate=data?.candidates?.filter(x=>x.status==='FEASIBLE'||x.status==='OPTIMAL')[index];
 if(!candidate)return null;
 const p=createProject(site);
 p.items=candidate.rooms.map(r=>({...r}));
 const core=p.items.find(r=>r.type==='core');
 if(core)p.entrance={kind:'proposed unit entry',x:core.x+core.w/2,y:core.y};
 p.solver={name:data.engine,status:candidate.status,siteId:site.id,variant:candidate.variant,
   generation:'CI-precomputed, NOT live solving',unverified:candidate.not_checked,metrics:candidate.metrics};
 return p;
}
function unsupportedProject(site,data){
 const p=createProject(site);p.items=[];
 p.solver={name:'NO SOLVER RESULT',status:'UNSUPPORTED',reason:data?.candidates?.[0]?.reason||'No verified model for this site yet'};
 return p;
}
